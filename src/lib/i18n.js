const DICTS = { my, en };

/** Lookup "a.b.c" in the dictionary; returns the key itself when missing. */
function t(lang, key) {
  const dict = DICTS[lang] || DICTS.my;
  const parts = key.split(".");
  let node = dict;
  for (const p of parts) {
    if (node == null || typeof node !== "object") return key;
    node = node[p];
  }
  return typeof node === "string" ? node : key;
}

function isLang(v) {
  return v === "my" || v === "en";
}

